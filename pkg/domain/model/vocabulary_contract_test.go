package model_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"

	"github.com/carolsimone/continuo/pkg/domain/model"
)

// contractPath locates the single source of truth for every vocabulary. The
// YAML lives next to the stream contract because one generator run emits both
// surfaces; the generated vocabulary types land here, in the shared domain
// package, so domain code never imports the transport package.
func contractPath() string {
	return filepath.Join("..", "..", "streams", "contract.yaml")
}

type yamlVocabularies struct {
	Vocabularies []struct {
		Const  string `yaml:"const"`
		Values []struct {
			Value    string `yaml:"value"`
			Healable bool   `yaml:"healable"`
		} `yaml:"values"`
	} `yaml:"vocabularies"`
}

func loadVocabularies(t *testing.T) yamlVocabularies {
	t.Helper()
	data, err := os.ReadFile(contractPath())
	if err != nil {
		t.Fatalf("read contract.yaml: %v", err)
	}
	var c yamlVocabularies
	if err := yaml.Unmarshal(data, &c); err != nil {
		t.Fatalf("parse contract.yaml: %v", err)
	}
	if len(c.Vocabularies) == 0 {
		t.Fatal("contract.yaml declares no vocabularies")
	}
	return c
}

func TestGeneratedVocabulariesMatchContract(t *testing.T) {
	c := loadVocabularies(t)
	gen := model.VocabularyValuesForTest()
	if len(gen) != len(c.Vocabularies) {
		t.Errorf("yaml declares %d vocabularies, generated package has %d", len(c.Vocabularies), len(gen))
	}
	for _, v := range c.Vocabularies {
		got, ok := gen[v.Const]
		if !ok {
			t.Errorf("vocabulary %s missing from generated package", v.Const)
			continue
		}
		if len(got) != len(v.Values) {
			t.Errorf("vocabulary %s: yaml has %d values, generated has %d", v.Const, len(v.Values), len(got))
			continue
		}
		for i, val := range v.Values {
			if got[i] != val.Value {
				t.Errorf("vocabulary %s[%d]: yaml=%q generated=%q", v.Const, i, val.Value, got[i])
			}
		}
	}
}

