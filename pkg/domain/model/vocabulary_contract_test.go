func TestParseFailureKind_ContractOrderAndHealable(t *testing.T) {
	kinds := model.ParseFailureKinds()
	want := []model.ParseFailureKind{
		model.ParseFailureKindInvalidSQL,
		model.ParseFailureKindUnqualifiedReference,
		model.ParseFailureKindInvalidArtifact,
		model.ParseFailureKindInternal,
	}
	if len(kinds) != len(want) {
		t.Fatalf("ParseFailureKinds() = %v, want %v", kinds, want)
	}
	for i := range want {
		if kinds[i] != want[i] {
			t.Errorf("index %d: %q, want %q", i, kinds[i], want[i])
		}
		if !kinds[i].IsValid() {
			t.Errorf("%q must be valid", kinds[i])
		}
	}
	if !model.ParseFailureKindInvalidSQL.Healable() || !model.ParseFailureKindUnqualifiedReference.Healable() {
		t.Error("both SQL kinds must be healable")
	}
	if model.ParseFailureKindInvalidArtifact.Healable() || model.ParseFailureKindInternal.Healable() {
		t.Error("artifact and internal kinds must not be healable")
	}
	if model.ParseFailureKind("nonsense").IsValid() {
		t.Error("an undeclared value must not be valid")
	}
}

// TestVocabularyHealableFlagsMatchContract pins every generated Healable()
// answer to the healable: flag the YAML declares for that value.
func TestVocabularyHealableFlagsMatchContract(t *testing.T) {
	c := loadVocabularies(t)
	healableByType := map[string]func(string) bool{
		"ParseFailureKind": func(v string) bool { return model.ParseFailureKind(v).Healable() },
	}
	for _, v := range c.Vocabularies {
		healable, ok := healableByType[v.Const]
		if !ok {
			t.Errorf("vocabulary %s has no Healable() probe in this test — add one", v.Const)
			continue
		}
		for _, val := range v.Values {
			if got := healable(val.Value); got != val.Healable {
				t.Errorf("%s(%q).Healable() = %v, yaml says %v", v.Const, val.Value, got, val.Healable)
			}
		}
	}
}
