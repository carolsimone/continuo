package streams_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"

	"github.com/carolsimone/continuo/pkg/streams"
)

type yamlContract struct {
	Streams []struct {
		Name      string `yaml:"name"`
		Const     string `yaml:"const"`
		Consumers []struct {
			Group string `yaml:"group"`
			Const string `yaml:"const"`
		} `yaml:"consumers"`
	} `yaml:"streams"`
}

func TestGeneratedGoMatchesContract(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("contract.yaml"))
	if err != nil {
		t.Fatalf("read contract.yaml: %v", err)
	}
	var c yamlContract
	if err := yaml.Unmarshal(data, &c); err != nil {
		t.Fatalf("parse contract.yaml: %v", err)
	}

	pkgVals := streams.PkgConstantsForTest()

	for _, s := range c.Streams {
		got, ok := pkgVals[s.Const]
		if !ok {
			t.Errorf("stream const %s missing from generated package", s.Const)
			continue
		}
		if got != s.Name {
			t.Errorf("stream const %s: yaml=%q generated=%q", s.Const, s.Name, got)
		}
		for _, cons := range s.Consumers {
			gg, ok := pkgVals[cons.Const]
			if !ok {
				t.Errorf("group const %s missing from generated package", cons.Const)
				continue
			}
			if gg != cons.Group {
				t.Errorf("group const %s: yaml=%q generated=%q", cons.Const, cons.Group, gg)
			}
		}
	}
}

func TestGeneratedFileHeader(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("streams.gen.go"))
	if err != nil {
		t.Fatalf("read streams.gen.go: %v", err)
	}
	if !strings.Contains(string(data), "// Code generated by gen-streams. DO NOT EDIT.") {
		t.Fatal("streams.gen.go missing generated header")
	}
}
